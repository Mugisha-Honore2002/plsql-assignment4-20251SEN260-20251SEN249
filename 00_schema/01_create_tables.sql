-- Tables, relationships, constraints, indexes and SQL types.
-- Re-runnable: drops existing objects first.
-- =====================================================================
SET SERVEROUTPUT ON SIZE UNLIMITED;

BEGIN
  FOR r IN (SELECT 'DROP TABLE ' || table_name || ' CASCADE CONSTRAINTS PURGE' AS stmt
              FROM user_tables
             WHERE table_name IN ('IMPORT_ERROR_LOG','GRADE_IMPORT_STAGING','GRADE_AUDIT',
                                  'ENROLLMENTS','COURSES','STUDENTS','DEPARTMENTS','PERF_TEST'))
  LOOP
    EXECUTE IMMEDIATE r.stmt;
  END LOOP;
  FOR r IN (SELECT 'DROP TYPE ' || type_name || ' FORCE' AS stmt
              FROM user_types
             WHERE type_name IN ('T_TRANSCRIPT_TAB','T_TRANSCRIPT_OBJ'))
  LOOP
    EXECUTE IMMEDIATE r.stmt;
  END LOOP;
END;
/

-- ---------------------------------------------------------------------
-- DEPARTMENTS
-- ---------------------------------------------------------------------
CREATE TABLE departments (
  dept_id    NUMBER(4)     CONSTRAINT pk_departments PRIMARY KEY,
  dept_name  VARCHAR2(80)  NOT NULL CONSTRAINT uq_dept_name UNIQUE
);

-- ---------------------------------------------------------------------
-- STUDENTS  (many students -> one department)
-- ---------------------------------------------------------------------
CREATE TABLE students (
  student_id NUMBER(8) CONSTRAINT pk_students PRIMARY KEY,
  first_name VARCHAR2(50) NOT NULL,
  last_name VARCHAR2(50) NOT NULL,
  email VARCHAR2(100) NOT NULL CONSTRAINT uq_students_email UNIQUE,
  dept_id NUMBER(4) NOT NULL CONSTRAINT fk_students_dept REFERENCES departments(dept_id),
  enroll_date DATE DEFAULT SYSDATE NOT NULL,
  gpa NUMBER(3,2),
  status VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
  CONSTRAINT ck_students_status CHECK (status IN ('ACTIVE','SUSPENDED','GRADUATED')),
  CONSTRAINT ck_students_gpa CHECK (gpa BETWEEN 0 AND 4)
);

-- ---------------------------------------------------------------------
-- COURSES  (many courses -> one department)
-- ---------------------------------------------------------------------
CREATE TABLE courses (
  course_id NUMBER(6) CONSTRAINT pk_courses PRIMARY KEY,
  course_code VARCHAR2(10) NOT NULL CONSTRAINT uq_course_code UNIQUE,
  title VARCHAR2(100) NOT NULL,
  credits NUMBER(1) NOT NULL,
  dept_id NUMBER(4) NOT NULL CONSTRAINT fk_courses_dept REFERENCES departments(dept_id),
  capacity NUMBER(3) NOT NULL,
  CONSTRAINT ck_courses_credits CHECK (credits BETWEEN 1 AND 6),
  CONSTRAINT ck_courses_capacity CHECK (capacity > 0)
);

-- ---------------------------------------------------------------------
-- ENROLLMENTS  (students <-> courses, many-to-many, per semester)
-- ---------------------------------------------------------------------
CREATE TABLE enrollments (
  enrollment_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                CONSTRAINT pk_enrollments PRIMARY KEY,
  student_id NUMBER(8) NOT NULL CONSTRAINT fk_enr_student REFERENCES students(student_id),
  course_id NUMBER(6) NOT NULL CONSTRAINT fk_enr_course  REFERENCES courses(course_id),
  semester VARCHAR2(10) NOT NULL,
  enroll_date DATE DEFAULT SYSDATE NOT NULL,
  grade_score NUMBER(5,2),
  letter_grade VARCHAR2(2),
  CONSTRAINT uq_enrollment UNIQUE (student_id, course_id, semester),
  CONSTRAINT ck_enr_semester CHECK (REGEXP_LIKE(semester, '^[0-9]{4}-(SPRING|SUMMER|FALL)$')),
  CONSTRAINT ck_enr_score CHECK (grade_score BETWEEN 0 AND 100),
  CONSTRAINT ck_enr_letter CHECK (letter_grade IN ('A','B','C','D','F'))
);

-- ---------------------------------------------------------------------
-- GRADE_AUDIT  (history of grade changes; no FK so history survives deletes)
-- ---------------------------------------------------------------------
CREATE TABLE grade_audit (
  audit_id NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT pk_grade_audit PRIMARY KEY,
  enrollment_id NUMBER NOT NULL,
  old_score NUMBER(5,2),
  new_score NUMBER(5,2),
  changed_by VARCHAR2(30) DEFAULT USER NOT NULL,
  changed_on TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- ---------------------------------------------------------------------
-- GRADE_IMPORT_STAGING  (raw grades from a spreadsheet/LMS, to be bulk-loaded)
-- score is wider than grade_score on purpose, so bad data (e.g. 150) can be staged
-- ---------------------------------------------------------------------
CREATE TABLE grade_import_staging (
  staging_id NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT pk_grade_staging PRIMARY KEY,
  student_id NUMBER(8) NOT NULL,
  course_id NUMBER(6) NOT NULL,
  semester VARCHAR2(10) NOT NULL,
  score NUMBER(6,2) NOT NULL,
  processed CHAR(1) DEFAULT 'N' NOT NULL,
  CONSTRAINT ck_staging_processed CHECK (processed IN ('Y','N'))
);

-- ---------------------------------------------------------------------
-- IMPORT_ERROR_LOG  (rows that failed during the bulk import)
-- ---------------------------------------------------------------------
CREATE TABLE import_error_log (
  log_id NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT pk_import_error_log PRIMARY KEY,
  staging_id NUMBER NOT NULL,
  error_code NUMBER NOT NULL,
  error_message VARCHAR2(500) NOT NULL,
  logged_on TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- ---------------------------------------------------------------------
-- PERF_TEST  (scratch table for the loop-vs-FORALL benchmark)
-- ---------------------------------------------------------------------
CREATE TABLE perf_test (
  id NUMBER,
  payload VARCHAR2(50),
  created DATE
);

-- ---------------------------------------------------------------------
-- Indexes (FKs and frequent lookups)
-- ---------------------------------------------------------------------
CREATE INDEX idx_students_dept ON students(dept_id);
CREATE INDEX idx_students_lastname ON students(UPPER(last_name));
CREATE INDEX idx_courses_dept ON courses(dept_id);
CREATE INDEX idx_enr_course_sem ON enrollments(course_id, semester);
CREATE INDEX idx_staging_sem ON grade_import_staging(semester, processed);

-- ---------------------------------------------------------------------
-- SQL types (needed so a function can return a collection usable in SQL)
-- ---------------------------------------------------------------------
CREATE OR REPLACE TYPE t_transcript_obj AS OBJECT (
  course_code VARCHAR2(10),
  title VARCHAR2(100),
  credits NUMBER,
  semester VARCHAR2(10),
  grade_score NUMBER,
  letter_grade VARCHAR2(2)
);
/
CREATE OR REPLACE TYPE t_transcript_tab AS TABLE OF t_transcript_obj;
